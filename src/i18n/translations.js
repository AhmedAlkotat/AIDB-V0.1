function lookup(dictionary, key) {
  return key
    .split('.')
    .reduce((node, part) => (node && typeof node === 'object' ? node[part] : undefined), dictionary)
}

// Resolves a dotted key (e.g. "nav.dashboard") for a language, falling back to
// the default language, then to the key itself. "{name}" placeholders are
// replaced with values from `params`.
export function translate(language, key, params) {
  let value = lookup(translations[language], key)
  if (typeof value !== 'string') {
    value = lookup(translations[defaultLanguage], key)
  }
  if (typeof value !== 'string') {
    if (import.meta.env.DEV) {
      console.warn(`Missing translation for key: ${key}`)
    }
    return key
  }
  if (!params) {
    return value
  }
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(params, name) ? String(params[name]) : match,
  )
}

export function formatNumber(value, language) {
  return new Intl.NumberFormat(language).format(value)
}

// A date and time (ISO string or Date) in the language's own style; invalid gives an empty string.
export function formatDateTime(value, language) {
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '' : new Intl.DateTimeFormat(language, { dateStyle: 'medium', timeStyle: 'short' }).format(date)
}

// A date (ISO string or Date) in the language's own style; an invalid value gives an empty string.
export function formatDate(value, language) {
  const date = new Date(value)
  return Number.isNaN(date.getTime()) ? '' : new Intl.DateTimeFormat(language, { dateStyle: 'medium' }).format(date)
}
